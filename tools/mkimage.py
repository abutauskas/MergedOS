def sample_png_pixel(x, y):
    if (x - 20) ** 2 + (y - 24) ** 2 <= 12 ** 2:        # sun disc
        return (255, 200, 40)
    if 36 <= x <= 56 and 10 <= y <= 38:                 # green block
        return (30, 160, 120)
    return (40 + x * 3, 60 + y * 3, 160)                # gradient


def png_chunk(kind, data):
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))


def make_png(w, h, pixel):
    """8-bit RGB, non-interlaced; rows use all five filter types in turn."""
    raw, prev = bytearray(), bytes(w * 3)
    for y in range(h):
        row = bytes(c for x in range(w) for c in pixel(x, y))
        ft = y % 5
        out = bytearray(len(row))
        for i, v in enumerate(row):
            a = row[i - 3] if i >= 3 else 0
            b = prev[i]
            c = prev[i - 3] if i >= 3 else 0
            if ft == 0:
                pred = 0
            elif ft == 1:
                pred = a
            elif ft == 2:
                pred = b
            elif ft == 3:
                pred = (a + b) // 2
            else:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pred = a if pa <= pb and pa <= pc else b if pb <= pc else c
            out[i] = (v - pred) & 0xFF
        raw += bytes([ft]) + out
        prev = row
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + png_chunk(b"IHDR", ihdr) +
            png_chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + png_chunk(b"IEND", b""))


def sample_bmp_pixel(x, y):
    if 10 <= x < 20 and 5 <= y < 15:
        return (255, 0, 0)
    return (x * 5, y * 8, 128)


def make_bmp(w, h, pixel):
    """24-bit, bottom-up, uncompressed (rows padded to 4 bytes)."""
    stride = (w * 3 + 3) & ~3
    data = bytearray()
    for y in reversed(range(h)):
        row = bytearray()
        for x in range(w):
            r, g, b = pixel(x, y)
            row += bytes((b, g, r))
        data += row + b"\0" * (stride - len(row))
    hdr = struct.pack("<2sIHHI", b"BM", 54 + len(data), 0, 0, 54)
    dib = struct.pack("<IiiHHIIiiII", 40, w, h, 1, 24, 0, len(data), 2835, 2835, 0, 0)
    return hdr + dib + bytes(data)


def make_wav():
    """One second of a 440 Hz square-ish tone, 8 kHz, 8-bit mono."""
    rate = 8000
    frames = bytes(200 if (i * 440 * 2 // rate) % 2 else 56 for i in range(rate))
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(1)
        w.setframerate(rate)
        w.writeframes(frames)
    return buf.getvalue()


def make_zip():
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        for name, text, method in (
                ("readme.txt", "MergedOS sample archive.\n" * 8, zipfile.ZIP_DEFLATED),
                ("notes/hello.txt", "hello from inside a zip\n", zipfile.ZIP_STORED)):
            info = zipfile.ZipInfo(name, date_time=(2024, 1, 1, 0, 0, 0))
            info.compress_type = method
            info.external_attr = 0o644 << 16
            z.writestr(info, text)
    return buf.getvalue()


def make_pdf():
    """A one-page PDF with a correct cross-reference table."""
    stream = b"BT /F1 18 Tf 20 40 Td (Hello from MergedOS) Tj ET"
    objs = [b"<< /Type /Catalog /Pages 2 0 R >>",
            b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 240 100] /Contents 4 0 R "
            b"/Resources << /Font << /F1 5 0 R >> >> >>",
            b"<< /Length %d >>\nstream\n%s\nendstream" % (len(stream), stream),
            b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"]
    out, offs = bytearray(b"%PDF-1.4\n"), []
    for i, body in enumerate(objs, 1):
        offs.append(len(out))
        out += b"%d 0 obj\n%s\nendobj\n" % (i, body)
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1)
    out += b"".join(b"%010d 00000 n \n" % o for o in offs)
    out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objs) + 1, xref)
    return bytes(out)


