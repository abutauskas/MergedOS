def read(path):
    with open(path, "rb") as f:
        return f.read()


def build_tree(guest_dir, src_dir):
    """Return {initrd path: (data, mode)} in a stable order."""
    elf = read(os.path.join(guest_dir, "hello.linux"))
    macho = read(os.path.join(guest_dir, "hello.macho"))
    plist = read(os.path.join(src_dir, "Hello.app", "Contents", "Info.plist"))
    extra = {}
    demo = os.path.join(guest_dir, "demo.musl")
    if os.path.exists(demo) and os.path.getsize(demo):       # only when musl-gcc was available
        extra["bin/demo.musl"] = (read(demo), 0o755)
    win = os.path.join(guest_dir, "win_hello.exe")
    if os.path.exists(win) and os.path.getsize(win):        # only when MinGW-w64 was available
        extra["bin/win_hello.exe"] = (read(win), 0o755)
    wine = os.path.join(guest_dir, "wine")                  # optional: make WINE_EXE_DIR=...
    if os.path.isdir(wine):
        for name in sorted(os.listdir(wine)):
            if name.endswith(".exe"):
                extra["bin/wine/" + name] = (read(os.path.join(wine, name)), 0o755)
    return {
        **samples(),
        **extra,
        "bin/hello.linux": (elf, 0o755),
        "bin/hello.freebsd": (read(os.path.join(guest_dir, "hello.freebsd")), 0o755),
        "bin/hello.macho": (macho, 0o755),
        "bin/hello.exe": (read(os.path.join(guest_dir, "hello.exe")), 0o755),
        "bin/spin.linux": (read(os.path.join(guest_dir, "spin.linux")), 0o755),
        "bin/proctest.linux": (read(os.path.join(guest_dir, "proctest.linux")), 0o755),
        "Applications/Hello.app/Contents/Info.plist": (plist, 0o644),
        "Applications/Hello.app/Contents/MacOS/hello": (macho, 0o755),
        "pkg/hello_1.0-1_amd64.deb": (make_deb(elf), 0o644),
        "pkg/hello-1.0-1.x86_64.rpm": (make_rpm(elf), 0o644),
        "pkg/hello-1.0-r0.apk": (make_apk(elf), 0o644),
        "pkg/hello-1.0-1-x86_64.pkg.tar.gz": (make_pacman(elf), 0o644),
        "etc/motd": (MOTD, 0o644),
        "etc/mergedfence/default.merged": (fence_default(), 0o644),
    }


def cmd_initrd(args):
    tree = build_tree(args.guest_dir, args.src_dir)
    members, seen = [], set()
    for path, (data, mode) in tree.items():
        parts = path.split("/")[:-1]
        for i in range(1, len(parts) + 1):
            d = "/".join(parts[:i]) + "/"
            if d not in seen:
                seen.add(d)
                members.append((d, b"", 0o755))
        members.append((path, data, mode))
    blob = ustar(members)
    with open(args.out, "wb") as f:
        f.write(blob)
    print(f"mkimage: {args.out}: {len(tree)} files, {len(blob)} bytes")


