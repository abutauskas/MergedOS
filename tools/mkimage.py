def make_merged(manifest, payload):
    """A native .merged package: header, manifest, payload, SHA-256 trailer."""
    man = "".join(f"{k}: {v}\n" for k, v in manifest).encode()
    body = b"MRGD" + struct.pack("<III", 1, len(man), len(payload)) + man + payload
    return body + hashlib.sha256(body).digest()


