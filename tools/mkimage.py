def ustar(members, terminate=True):
    """members: iterable of (path, data, mode). Directories end with '/'."""
    out = bytearray()
    for path, data, mode in members:
        is_dir = path.endswith("/")
        name = path.encode()
        if len(name) > 100:
            raise ValueError(f"path too long for this simple ustar writer: {path}")
        hdr = bytearray(512)
        hdr[0:len(name)] = name
        hdr[100:108] = b"%07o\0" % mode
        hdr[108:116] = b"0000000\0"                      # uid
        hdr[116:124] = b"0000000\0"                      # gid
        hdr[124:136] = b"%011o\0" % (0 if is_dir else len(data))
        hdr[136:148] = b"00000000000\0"                  # mtime (fixed: reproducible)
        hdr[148:156] = b" " * 8                          # checksum placeholder
        hdr[156] = ord("5" if is_dir else "0")
        hdr[257:263] = b"ustar\0"
        hdr[263:265] = b"00"
        hdr[265:269] = b"root"
        hdr[297:301] = b"root"
        hdr[148:156] = b"%06o\0 " % sum(hdr)
        out += hdr
        if not is_dir:
            out += data + b"\0" * (-len(data) % 512)
    if terminate:
        out += b"\0" * 1024
    return bytes(out)


def gz(data):
    return gzip.compress(data, compresslevel=9, mtime=0)


def ar(members):
    out = bytearray(b"!<arch>\n")
    for name, data in members:
        out += b"%-16s%-12d%-6d%-6d%-8s%-10d`\n" % (name.encode(), 0, 0, 0, b"100644", len(data))
        out += data
        if len(data) % 2:
            out += b"\n"
    return bytes(out)


def cpio_newc(members):
    """members: iterable of (path, data, mode)."""
    out = bytearray()
    ino = 1

    def entry(path, data, mode, nlink):
        nonlocal ino
        name = path.encode() + b"\0"
        fields = (ino, mode, 0, 0, nlink, 0, len(data), 0, 0, 0, 0, len(name), 0)
        blob = b"070701" + b"".join(b"%08X" % f for f in fields) + name
        blob += b"\0" * (-len(blob) % 4)
        blob += data + b"\0" * (-len(data) % 4)
        ino += 1
        return blob

    for path, data, mode in members:
        out += entry(path, data, 0o100000 | mode, 1)
    out += entry("TRAILER!!!", b"", 0, 1)
    return bytes(out)


