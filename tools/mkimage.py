RPM_INT32, RPM_STRING, RPM_BIN, RPM_STRING_ARRAY, RPM_I18NSTRING = 4, 6, 7, 8, 9


def rpm_header(entries, region_tag):
    """entries: list of (tag, type, count, data). Returns one RPM header blob."""
    store = bytearray()
    index = []
    for tag, typ, count, data in sorted(entries):
        if typ == RPM_INT32:
            store += b"\0" * (-len(store) % 4)
        index.append((tag, typ, len(store), count))
        store += data
    # Immutable-region marker: first index entry points at a trailer that
    # mirrors it with a negative offset covering the whole index.
    nindex = len(index) + 1
    index.insert(0, (region_tag, RPM_BIN, len(store), 16))
    store += struct.pack(">IIiI", region_tag, RPM_BIN, -(nindex * 16), 16)
    out = bytearray(b"\x8e\xad\xe8\x01\0\0\0\0")
    out += struct.pack(">II", len(index), len(store))
    for tag, typ, off, count in index:
        out += struct.pack(">IIII", tag, typ, off, count)
    return bytes(out + store)


def make_rpm(elf):
    def s(text):
        return text.encode() + b"\0"

    def sa(items):
        return b"".join(s(i) for i in items)

    requires = [("/bin/sh", "", 0), ("glibc", "2.34", 0x0C),            # >=
                ("libc.so.6(GLIBC_2.2.5)(64bit)", "", 0),
                ("rpmlib(CompressedFileNames)", "3.0.4-1", 0x0100000A)]  # rpmlib | <=
    payload = gz(cpio_newc([("./usr/bin/hello", elf, 0o755)]))
    header = rpm_header([
        (1000, RPM_STRING, 1, s("hello")),                      # NAME
        (1001, RPM_STRING, 1, s("1.0")),                        # VERSION
        (1002, RPM_STRING, 1, s("1")),                          # RELEASE
        (1004, RPM_I18NSTRING, 1, s(SUMMARY)),                  # SUMMARY
        (1005, RPM_I18NSTRING, 1, s("Static Linux x86-64 test executable.")),
        (1009, RPM_INT32, 1, struct.pack(">I", len(elf))),      # SIZE
        (1014, RPM_STRING, 1, s("BSD-2-Clause")),               # LICENSE
        (1016, RPM_I18NSTRING, 1, s("Unspecified")),            # GROUP
        (1021, RPM_STRING, 1, s("linux")),                      # OS
        (1022, RPM_STRING, 1, s("x86_64")),                     # ARCH
        (1048, RPM_INT32, len(requires), b"".join(struct.pack(">I", f) for _, _, f in requires)),
        (1049, RPM_STRING_ARRAY, len(requires), sa(n for n, _, _ in requires)),
        (1050, RPM_STRING_ARRAY, len(requires), sa(v for _, v, _ in requires)),
        (1124, RPM_STRING, 1, s("cpio")),                       # PAYLOADFORMAT
        (1125, RPM_STRING, 1, s("gzip")),                       # PAYLOADCOMPRESSOR
        (1126, RPM_STRING, 1, s("9")),                          # PAYLOADFLAGS
    ], region_tag=63)                                           # HEADERIMMUTABLE
    signature = rpm_header([
        (269, RPM_STRING, 1, s(hashlib.sha1(header).hexdigest())),              # SHA1
        (273, RPM_STRING, 1, s(hashlib.sha256(header).hexdigest())),            # SHA256
        (1000, RPM_INT32, 1, struct.pack(">I", len(header) + len(payload))),    # SIZE
        (1004, RPM_BIN, 16, hashlib.md5(header + payload).digest()),            # MD5
    ], region_tag=62)                                           # HEADERSIGNATURES
    signature += b"\0" * (-len(signature) % 8)
    lead = struct.pack(">4sBBhh66shh16s", b"\xed\xab\xee\xdb", 3, 0, 0, 1,
                       b"hello-1.0-1", 1, 5, b"")
    return lead + signature + header + payload


