def make_deb(elf):
    control = (
        "Package: hello\n"
        "Version: 1.0-1\n"
        "Architecture: amd64\n"
        f"Maintainer: {MAINTAINER}\n"
        "Installed-Size: 4\n"
        "Depends: libc6 (>= 2.34), libgcc-s1 | libgcc1, zlib1g\n"
        "Section: misc\n"
        "Priority: optional\n"
        f"Description: {SUMMARY}\n"
        " Static Linux x86-64 executable used to exercise .deb translation.\n"
    ).encode()
    postinst = b"#!/bin/sh\nset -e\nexit 0\n"
    control_tar = ustar([("./", b"", 0o755), ("./control", control, 0o644),
                         ("./postinst", postinst, 0o755)])
    data_tar = ustar([
        ("./", b"", 0o755), ("./usr/", b"", 0o755), ("./usr/bin/", b"", 0o755),
        ("./usr/bin/hello", elf, 0o755),
        ("./usr/share/", b"", 0o755), ("./usr/share/doc/", b"", 0o755),
        ("./usr/share/doc/hello/", b"", 0o755),
        ("./usr/share/doc/hello/copyright", b"BSD-2-Clause\n", 0o644),
    ])
    return ar([("debian-binary", b"2.0\n"), ("control.tar.gz", gz(control_tar)),
               ("data.tar.gz", gz(data_tar))])


def make_apk(elf):
    pkginfo = (
        "# Generated by abuild 3.13.0-r5\n"
        "pkgname = hello\n"
        "pkgver = 1.0-r0\n"
        f"pkgdesc = {SUMMARY}\n"
        "url = https://example.invalid/hello\n"
        "builddate = 0\n"
        f"packager = {MAINTAINER}\n"
        "size = 4096\n"
        "arch = x86_64\n"
        "origin = hello\n"
        "license = BSD-2-Clause\n"
        "depend = so:libc.musl-x86_64.so.1\n"
        "depend = busybox\n"
        "datahash = " + hashlib.sha256(elf).hexdigest() + "\n"
    ).encode()
    # An .apk is three concatenated gzip streams: signature, control, data.
    # The first two are tar *segments* without an end-of-archive marker.
    sig = ustar([(".SIGN.RSA.fixtures@mergedos.rsa.pub", b"\0" * 256, 0o644)], terminate=False)
    ctl = ustar([(".PKGINFO", pkginfo, 0o644)], terminate=False)
    data = ustar([("usr/", b"", 0o755), ("usr/bin/", b"", 0o755), ("usr/bin/hello", elf, 0o755)])
    return gz(sig) + gz(ctl) + gz(data)


