const char *wizard_str(enum wiz_lang lang, enum wiz_str id)
{
	if ((unsigned)lang >= LANG_COUNT || (unsigned)id >= STR_COUNT || !strings[lang][id])
		return strings[LANG_EN][(unsigned)id < STR_COUNT ? id : STR_WELCOME];
	return strings[lang][id];
}

const char *wizard_lang_name(enum wiz_lang lang)
{
	return names[(unsigned)lang < LANG_COUNT ? lang : LANG_EN];
}
